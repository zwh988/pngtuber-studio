<!--
  Voice model page (M7 S3): the first-run screen. Says how big the download is and
  where it goes, then shows progress, a Retry after a failure, and "ready".
  Presentational: App.svelte owns the status and polls it while a download runs.
-->
<script lang="ts">
  import { Download, RefreshCw } from "@lucide/svelte";
  import type { ModelStatus } from "./api";
  import { formatBytes } from "./voice";
  import Banner from "./ui/Banner.svelte";
  import Button from "./ui/Button.svelte";

  type Props = {
    status: ModelStatus;
    busy?: boolean;
    ondownload: () => void;
    /** Leave this page (the download, if running, carries on). */
    onleave: () => void;
  };

  let { status, busy = false, ondownload, onleave }: Props = $props();

  const fraction = $derived(
    status.bytes_total > 0 ? Math.min(1, status.bytes_done / status.bytes_total) : 0,
  );
  const left = $derived(Math.max(0, status.bytes_total - status.bytes_done));
  const fileIndex = $derived(Math.min(status.files_total, status.files_present + 1));
</script>

<div class="page-head">
  <div class="title">
    <h1>Voice model</h1>
    <div class="muted">
      Your lines are generated by Chatterbox, a voice model that runs on your GPU. It is
      downloaded once; after that the app works offline.
    </div>
  </div>
</div>

<section class="card">
  <div class="card-head">
    <h2>
      {#if status.state === "ready"}Ready{:else if status.state === "downloading"}Downloading{:else}Download
        the voice model{/if}
    </h2>
  </div>
  <div class="body">
    <dl class="facts">
      <dt>Size</dt>
      <dd class="num">
        {formatBytes(status.bytes_total)} in {status.files_total} files{#if status.state !== "ready" && status.bytes_done > 0}{` (${formatBytes(left)} still to download)`}{/if}
      </dd>
      <dt>Saved in</dt>
      <dd class="path">{status.cache_dir || "the Hugging Face cache"}</dd>
      <dt>Version</dt>
      <dd class="path">{status.repo} at {status.revision.slice(0, 8)}</dd>
    </dl>

    {#if status.state === "downloading"}
      <div
        class="bar"
        role="progressbar"
        aria-label="Voice model download"
        aria-valuemin="0"
        aria-valuemax="100"
        aria-valuenow={Math.round(fraction * 100)}
      >
        <div class="fill" style:width={`${(fraction * 100).toFixed(1)}%`}></div>
      </div>
      <p class="muted small num">
        {formatBytes(status.bytes_done)} of {formatBytes(status.bytes_total)} ({Math.round(
          fraction * 100,
        )}%) · file {fileIndex} of {status.files_total}{#if status.current_file}: {status.current_file}{/if}
      </p>
      <p class="muted small">
        You can keep working while it downloads. If it stops, Retry carries on from where it got to.
      </p>
    {:else if status.state === "failed"}
      <Banner kind="error">
        {status.message ?? "The download stopped."}
        {#snippet action()}
          <Button size="sm" icon={RefreshCw} onclick={ondownload} disabled={busy}>Retry</Button>
        {/snippet}
      </Banner>
    {:else if status.state === "ready"}
      <Banner kind="success">
        The voice model is on this PC. The first line you generate after starting the app takes a
        little longer while the model loads onto the GPU.
      </Banner>
    {:else}
      <p class="muted">
        Editing footage and exporting work without it; generating lines needs it. Use a stable
        connection: the download can be retried, and finished files are kept.
      </p>
    {/if}

    <div class="actions">
      {#if status.state === "missing"}
        <Button variant="primary" icon={Download} onclick={ondownload} disabled={busy}>
          Download ({formatBytes(status.bytes_total)})
        </Button>
        <Button variant="ghost" onclick={onleave}>Later</Button>
      {:else if status.state === "ready"}
        <Button variant="primary" onclick={onleave}>Continue</Button>
      {:else}
        <Button variant="ghost" onclick={onleave}>Back to projects</Button>
      {/if}
    </div>
  </div>
</section>

